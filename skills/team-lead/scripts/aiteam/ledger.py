"""The ledger: JSON is the source of truth, the markdown file a generated view."""

from __future__ import annotations

import json
import os
import re
import time
from typing import Any, Dict, List, Optional

from . import model
from .project import read_text

Ledger = Dict[str, Any]


def _abs(root: str, rel: str) -> str:
    return os.path.join(root, *rel.split("/"))


def write_text(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    os.replace(tmp, path)


def write_view(path: str, content: str) -> bool:
    """The generated markdown view: a viewer holding it open must not stop the pipeline."""
    try:
        write_text(path, content)
        return True
    except OSError:
        return False


def new_ledger(slug: str, request: str, workflow: str, base: Optional[str], start_point: str,
               lane: str = "full") -> Ledger:
    stages = {}
    for st in model.STAGES:
        stages[str(st.number)] = {"status": "PENDING", "skip_reason": None, "decided_from": None,
                                  "done_seq": None, "done_round": None, "dispatches": []}
    return {
        "schema": model.LEDGER_SCHEMA,
        "pipeline_version": model.PIPELINE_VERSION,
        "slug": slug,
        "request": request,
        "lane": lane,
        "gate_status": "IN_PROGRESS",
        "round": 0,
        "seq": 0,
        "counters": {"tests": 0, "security": 0, "escalations": 0},
        "design_gate": "PENDING",
        "mockup_gate": "PENDING",
        "approved_design": None,
        "approved_mockup": None,
        "workflow": {"kind": workflow, "base": base},
        "start_point": start_point,
        "shelved_stash": None,
        "stages": stages,
        "active_defects": [],
        "fast_path": None,
        "routed": [],
        "awaiting": None,
        "directions": {},
        "merge": None,
        "reviewed_change_record": None,
        "delivered_commit": None,
        "review_again_streak": 0,
        "imported_round": None,
        "notices": [],
        "history": [],
    }


def exists(root: str, slug: str) -> bool:
    return os.path.isfile(_abs(root, model.ledger_json_path(slug)))


def load(root: str, slug: str) -> Ledger:
    path = _abs(root, model.ledger_json_path(slug))
    text = read_text(path)
    if text is None:
        raise FileNotFoundError(f"no ledger for '{slug}' at {model.ledger_json_path(slug)}")
    return json.loads(text)


def save(root: str, led: Ledger) -> None:
    slug = led["slug"]
    write_text(_abs(root, model.ledger_json_path(slug)), json.dumps(led, indent=2, ensure_ascii=False) + "\n")
    if not write_view(_abs(root, model.ledger_md_path(slug)), render_markdown(led)):
        notice(led, f"{model.ledger_md_path(slug)} could not be rewritten (is it open somewhere?); "
                    f"the JSON ledger is current.")


def next_seq(led: Ledger) -> int:
    led["seq"] = int(led.get("seq", 0)) + 1
    return led["seq"]


def history(led: Ledger, line: str) -> None:
    stamp = time.strftime("%Y-%m-%d %H:%M")
    led.setdefault("history", []).append(f"{stamp} · {line}")


def notice(led: Ledger, line: str) -> None:
    led.setdefault("notices", []).append(line)


def stage_rec(led: Ledger, number: int) -> Dict[str, Any]:
    return led["stages"][str(number)]


def current_stage(led: Ledger) -> int:
    for st in model.STAGES:
        if stage_rec(led, st.number)["status"] not in ("DONE", "SKIPPED"):
            return st.number
    return model.LAST_STAGE + 1


def dispatches_in_round(led: Ledger, number: int, rnd: Optional[int] = None) -> List[Dict[str, Any]]:
    rnd = led["round"] if rnd is None else rnd
    return [d for d in stage_rec(led, number).get("dispatches", []) if d.get("round") == rnd]


def counters_text(led: Ledger) -> str:
    c = led["counters"]
    return (f"tests {c['tests']}/{model.CAPS['tests']}, security {c['security']}/{model.CAPS['security']}, "
            f"escalations {c['escalations']}/{model.CAPS['escalations']}")


def render_markdown(led: Ledger) -> str:
    cur = current_stage(led)
    cur_text = model.stage(cur).label if cur <= model.LAST_STAGE else "none"
    approved = led.get("approved_design")
    approved_text = (f"spec r{approved.get('spec')}, ADR r{approved.get('adr')}" if approved else "none")
    wf = led.get("workflow") or {}
    wf_text = wf.get("kind", "?")
    if wf.get("kind") == "worktree" and wf.get("base"):
        wf_text = f"worktree, base {wf['base']}"
    awaiting = led.get("awaiting")
    lines = [
        f"# Pipeline State: {led['slug']}",
        "",
        f"> Generated by ai_team.py from `{led['slug']}-pipeline.json`, the source of truth. "
        "Do not edit this file.",
        "",
        f"- **Gate Status:** {led['gate_status']}",
        f"- **Current Stage:** {cur_text}",
        f"- **Round:** {led['round']}",
        f"- **Backward Routes:** {counters_text(led)}",
        f"- **Design Gate:** {led['design_gate']}",
        f"- **Mock-up Gate:** {led.get('mockup_gate') or 'none'}",
        f"- **Approved Design:** {approved_text}",
        f"- **Workflow:** {wf_text}",
        f"- **Start Point:** {led.get('start_point') or 'none'}",
        f"- **Shelved Stash:** {led.get('shelved_stash') or 'none'}",
        f"- **Waiting On:** {awaiting.get('summary', awaiting.get('kind')) if awaiting else 'nothing'}",
        "",
        "## Stages",
        "| Stage | Status |",
        "| :--- | :--- |",
    ]
    for st in model.STAGES:
        rec = stage_rec(led, st.number)
        status = rec["status"]
        if status == "SKIPPED" and rec.get("skip_reason"):
            status = f"SKIPPED ({rec['skip_reason']})"
        lines.append(f"| {st.label} | {status} |")
    lines += ["", "## Active Defects"]
    defects = led.get("active_defects") or []
    if not defects:
        lines.append("- none")
    for d in defects:
        target = model.stage(d["owner"]).label if d.get("owner") else "user"
        lines.append(f"- {d['kind']} -> {d['area']} ({target}): {d['line']} ({d.get('handoff') or 'user'})")
    if led.get("fast_path"):
        fp = led["fast_path"]
        lines += ["", "## Fast Path", f"- **Request:** {fp.get('request', '')}",
                  "- **Files:** " + (", ".join(f"`{f}`" for f in fp.get("files", [])) or "none")]
    lines += ["", "## History"]
    lines += [f"- {h}" for h in led.get("history", [])] or ["- none"]
    return "\n".join(lines) + "\n"


# Import of a ledger written by team-lead 10.x (pipeline 7.x) -----------------------------------

def import_markdown(text: str, slug: str) -> Ledger:
    def field(name: str) -> str:
        m = re.search(rf"^\s*-\s+\*\*{re.escape(name)}:\*\*\s*(.*)$", text, re.MULTILINE)
        return m.group(1).strip() if m else ""

    wf_raw = field("Workflow")
    base = None
    kind = "in-place"
    if wf_raw.lower().startswith("worktree"):
        kind = "worktree"
        m = re.search(r"base\s+`?([^`\s]+)`?", wf_raw)
        base = m.group(1) if m else None
    led = new_ledger(slug, "", kind, base, field("Start Point").strip("`") or "")
    def word(value: str) -> str:
        parts = value.replace("`", " ").replace("*", " ").split()
        return parts[0].upper() if parts else ""

    gate = word(field("Gate Status"))
    led["gate_status"] = gate if gate in model.GATE_STATUSES else "IN_PROGRESS"
    rnd = re.search(r"\d+", field("Round"))
    led["round"] = int(rnd.group()) if rnd else 0
    routes = field("Backward Routes")
    for key in ("tests", "security", "escalations"):
        m = re.search(rf"{key}\s+(\d+)", routes)
        if m:
            led["counters"][key] = int(m.group(1))
    dg = field("Design Gate")
    if "fast path" in dg.lower():
        led["design_gate"] = model.FAST_PATH_GATE
    else:  # anything but a clear APPROVED opens the gate again, which is the safe side
        led["design_gate"] = "APPROVED" if word(dg) == "APPROVED" else "PENDING"
    mg = word(field("Mock-up Gate"))
    led["mockup_gate"] = mg if mg in ("PENDING", "APPROVED", "SKIPPED") else None
    ad = field("Approved Design")
    m_spec, m_adr = re.search(r"spec\s*r(\d+)", ad, re.I), re.search(r"ADR\s*r(\d+)", ad, re.I)
    if m_spec or m_adr:
        led["approved_design"] = {"spec": int(m_spec.group(1)) if m_spec else None,
                                  "adr": int(m_adr.group(1)) if m_adr else None}
    stash = field("Shelved Stash").strip("`")
    led["shelved_stash"] = None if stash in ("", "none") else stash
    for st in model.STAGES:
        label = model.LEGACY_LABELS.get(st.number, st.label)
        m = re.search(rf"^\|\s*\**{re.escape(label)}\**\s*\|\s*([A-Z_]+)", text, re.MULTILINE)
        if m and m.group(1) in ("PENDING", "DONE", "SKIPPED"):
            rec = stage_rec(led, st.number)
            rec["status"] = m.group(1)
            if m.group(1) == "DONE":
                rec["done_seq"] = 0
                rec["done_round"] = led["round"]
            if m.group(1) == "SKIPPED":
                rec["skip_reason"] = "fast path" if "fast path" in field("Design Gate").lower() else "condition"
    section = re.search(r"^##\s+Fast Path\s*$(?P<body>.*?)(?=^##\s|\Z)", text, re.MULTILINE | re.DOTALL)
    if section and section.group("body").strip():
        body = section.group("body").strip()
        files = re.findall(r"`([^`]+)`", body)
        led["fast_path"] = {"request": body.splitlines()[0].lstrip("- ").strip(), "files": files}
        led["lane"] = "fast"
    hist = re.search(r"^##\s+History\s*$(?P<body>.*?)(?=^##\s|\Z)", text, re.MULTILINE | re.DOTALL)
    if hist:
        led["history"] = [ln.strip()[2:].strip() for ln in hist.group("body").splitlines()
                          if ln.strip().startswith("- ")]
        if led["history"]:
            first = led["history"][0]
            m = re.search(r"request:\s*(.+)$", first)
            led["request"] = (m.group(1) if m else first).strip()
            led["request_short"] = led["request"]
    defects = re.search(r"^##\s+Active Defects\s*$(?P<body>.*?)(?=^##\s|\Z)", text, re.MULTILINE | re.DOTALL)
    if defects:
        for ln in defects.group("body").splitlines():
            m = re.match(r"^\s*-\s+(\w+)\s*->\s*([^()]+?)\s*\(([^)]*)\):\s*(.*?)(?:\s*\(([^()]*)\))?\s*$", ln)
            if not m:
                continue
            area = model.normalize_area(m.group(2)) or "user"
            owner = model.AREA_OWNER.get(area)
            led["active_defects"].append({
                "id": len(led["active_defects"]) + 1, "kind": m.group(1), "area": area,
                "owner": owner, "route_to": owner, "line": m.group(4), "handoff": m.group(5),
                "seq": 0, "user": area == "user"})
    led["imported_round"] = led["round"]
    # 7.x routed every handoff of this round already: its items are in Active Defects or
    # were answered (History). Routing them again would block or duplicate them.
    for st in model.STAGES:
        rel = model.handoff_path(slug, st.number)
        if rel:
            led["routed"].append(f"{rel}@r{led['round']}")
    history(led, f"Imported from the 7.x markdown ledger; pipeline {model.PIPELINE_VERSION} from here on")
    return led
