"""The ledger: JSON is the source of truth, the markdown file a generated view."""

from __future__ import annotations

import json
import os
import time
from typing import Any, Dict, List, Optional

from . import model
from .project import read_text

Ledger = Dict[str, Any]


def _abs(root: str, rel: str) -> str:
    return os.path.join(root, *rel.split("/"))


def write_text(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    os.replace(tmp, path)


def write_view(path: str, content: str) -> bool:
    """The generated markdown view: a viewer holding it open must not stop the pipeline."""
    try:
        write_text(path, content)
        return True
    except OSError:
        return False


def new_ledger(slug: str, request: str, workflow: str, base: Optional[str], start_point: str,
               lane: str = "full") -> Ledger:
    stages = {}
    for st in model.STAGES:
        stages[str(st.number)] = {"status": "PENDING", "skip_reason": None, "decided_from": None,
                                  "done_seq": None, "done_round": None, "dispatches": []}
    return {
        "schema": model.LEDGER_SCHEMA,
        "pipeline_version": model.PIPELINE_VERSION,
        "slug": slug,
        "request": request,
        "lane": lane,
        "gate_status": "IN_PROGRESS",
        "round": 0,
        "seq": 0,
        "counters": {"tests": 0, "security": 0, "escalations": 0},
        "design_gate": "PENDING",
        "mockup_gate": "PENDING",
        "approved_design": None,
        "approved_mockup": None,
        "workflow": {"kind": workflow, "base": base},
        "start_point": start_point,
        "shelved_stash": None,
        "stages": stages,
        "active_defects": [],
        "fast_path": None,
        "routed": [],
        "awaiting": None,
        "directions": {},
        "merge": None,
        "reviewed_change_record": None,
        "delivered_commit": None,
        "review_again_streak": 0,
        "notices": [],
        "history": [],
    }


def exists(root: str, slug: str) -> bool:
    return os.path.isfile(_abs(root, model.ledger_json_path(slug)))


def load(root: str, slug: str) -> Ledger:
    path = _abs(root, model.ledger_json_path(slug))
    text = read_text(path)
    if text is None:
        raise FileNotFoundError(f"no ledger for '{slug}' at {model.ledger_json_path(slug)}")
    return json.loads(text)


def save(root: str, led: Ledger) -> None:
    slug = led["slug"]
    write_text(_abs(root, model.ledger_json_path(slug)), json.dumps(led, indent=2, ensure_ascii=False) + "\n")
    if not write_view(_abs(root, model.ledger_md_path(slug)), render_markdown(led)):
        notice(led, f"{model.ledger_md_path(slug)} could not be rewritten (is it open somewhere?); "
                    f"the JSON ledger is current.")


def next_seq(led: Ledger) -> int:
    led["seq"] = int(led.get("seq", 0)) + 1
    return led["seq"]


def history(led: Ledger, line: str) -> None:
    stamp = time.strftime("%Y-%m-%d %H:%M")
    led.setdefault("history", []).append(f"{stamp} · {line}")


def notice(led: Ledger, line: str) -> None:
    led.setdefault("notices", []).append(line)


def stage_rec(led: Ledger, number: int) -> Dict[str, Any]:
    return led["stages"][str(number)]


def current_stage(led: Ledger) -> int:
    for st in model.STAGES:
        if stage_rec(led, st.number)["status"] not in ("DONE", "SKIPPED"):
            return st.number
    return model.LAST_STAGE + 1


def dispatches_in_round(led: Ledger, number: int, rnd: Optional[int] = None) -> List[Dict[str, Any]]:
    rnd = led["round"] if rnd is None else rnd
    return [d for d in stage_rec(led, number).get("dispatches", []) if d.get("round") == rnd]


def counters_text(led: Ledger) -> str:
    c = led["counters"]
    return (f"tests {c['tests']}/{model.CAPS['tests']}, security {c['security']}/{model.CAPS['security']}, "
            f"escalations {c['escalations']}/{model.CAPS['escalations']}")


def render_markdown(led: Ledger) -> str:
    cur = current_stage(led)
    cur_text = model.stage(cur).label if cur <= model.LAST_STAGE else "none"
    approved = led.get("approved_design")
    approved_text = (f"spec r{approved.get('spec')}, ADR r{approved.get('adr')}" if approved else "none")
    wf = led.get("workflow") or {}
    wf_text = wf.get("kind", "?")
    if wf.get("kind") == "worktree" and wf.get("base"):
        wf_text = f"worktree, base {wf['base']}"
    awaiting = led.get("awaiting")
    lines = [
        f"# Pipeline State: {led['slug']}",
        "",
        f"> Generated by ai_team.py from `{led['slug']}-pipeline.json`, the source of truth. "
        "Do not edit this file.",
        "",
        f"- **Gate Status:** {led['gate_status']}",
        f"- **Current Stage:** {cur_text}",
        f"- **Round:** {led['round']}",
        f"- **Backward Routes:** {counters_text(led)}",
        f"- **Design Gate:** {led['design_gate']}",
        f"- **Mock-up Gate:** {led.get('mockup_gate') or 'none'}",
        f"- **Approved Design:** {approved_text}",
        f"- **Workflow:** {wf_text}",
        f"- **Start Point:** {led.get('start_point') or 'none'}",
        f"- **Shelved Stash:** {led.get('shelved_stash') or 'none'}",
        f"- **Waiting On:** {awaiting.get('summary', awaiting.get('kind')) if awaiting else 'nothing'}",
        "",
        "## Stages",
        "| Stage | Status |",
        "| :--- | :--- |",
    ]
    for st in model.STAGES:
        rec = stage_rec(led, st.number)
        status = rec["status"]
        if status == "SKIPPED" and rec.get("skip_reason"):
            status = f"SKIPPED ({rec['skip_reason']})"
        lines.append(f"| {st.label} | {status} |")
    lines += ["", "## Active Defects"]
    defects = led.get("active_defects") or []
    if not defects:
        lines.append("- none")
    for d in defects:
        target = model.stage(d["owner"]).label if d.get("owner") else "user"
        lines.append(f"- {d['kind']} -> {d['area']} ({target}): {d['line']} ({d.get('handoff') or 'user'})")
    if led.get("fast_path"):
        fp = led["fast_path"]
        lines += ["", "## Fast Path", f"- **Request:** {fp.get('request', '')}",
                  "- **Files:** " + (", ".join(f"`{f}`" for f in fp.get("files", [])) or "none")]
    lines += ["", "## History"]
    lines += [f"- {h}" for h in led.get("history", [])] or ["- none"]
    return "\n".join(lines) + "\n"
